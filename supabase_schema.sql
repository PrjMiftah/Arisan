-- 1. Buat tabel adnan_User jika belum ada
CREATE TABLE IF NOT EXISTS public."adnan_User" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    nama TEXT,
    no_hp TEXT,
    role TEXT DEFAULT 'anggota',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Pastikan kolom-kolom utama tersedia jika tabel sudah terlanjur dibuat sebelumnya
ALTER TABLE public."adnan_User" ADD COLUMN IF NOT EXISTS username TEXT;
ALTER TABLE public."adnan_User" ADD COLUMN IF NOT EXISTS password TEXT;
ALTER TABLE public."adnan_User" ADD COLUMN IF NOT EXISTS nama TEXT;
ALTER TABLE public."adnan_User" ADD COLUMN IF NOT EXISTS no_hp TEXT;
ALTER TABLE public."adnan_User" ADD COLUMN IF NOT EXISTS role TEXT DEFAULT 'anggota';
ALTER TABLE public."adnan_User" ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ DEFAULT NOW();

-- 3. Berikan hak akses (GRANT) ke role anon dan authenticated
-- (Mengatasi error 42501: permission denied for table adnan_User)
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT ALL PRIVILEGES ON TABLE public."adnan_User" TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

-- 4. Konfigurasi Row Level Security (RLS) agar REST API bisa membaca & menambah user
ALTER TABLE public."adnan_User" ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow anon select adnan_User" ON public."adnan_User";
CREATE POLICY "Allow anon select adnan_User"
    ON public."adnan_User"
    FOR SELECT
    TO anon, authenticated
    USING (true);

DROP POLICY IF EXISTS "Allow anon insert adnan_User" ON public."adnan_User";
CREATE POLICY "Allow anon insert adnan_User"
    ON public."adnan_User"
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon update adnan_User" ON public."adnan_User";
CREATE POLICY "Allow anon update adnan_User"
    ON public."adnan_User"
    FOR UPDATE
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

